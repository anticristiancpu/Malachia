const libri = db.prepare(`
  SELECT b.id, b.title, b.subtitle,
    (SELECT GROUP_CONCAT(a.name, '; ') FROM authors a
      JOIN book_authors ba ON a.id = ba.author_id WHERE ba.book_id = b.id) AS autori
  FROM books b
  WHERE (b.placement_id IS NULL OR b.placement_id = '') AND b.status <> 'wishlist'
`).all();

const assegnati = [];
const scoperti = [];

for (const l of libri) {
  const titolo = `${l.title} ${l.subtitle || ''}`.trim();
  let dove = null;
  for (const [re, sez] of PER_TITOLO) if (re.test(titolo)) { dove = sez; break; }
  if (!dove) dove = PER_AUTORE[(l.autori || '').trim()] || null;
  if (dove && isValidSection(dove)) assegnati.push({ id: l.id, dove, titolo: l.title, autori: l.autori });
  else scoperti.push(l);
}

// Riepilogo
const perSezione = {};
for (const a of assegnati) perSezione[a.dove] = (perSezione[a.dove] || 0) + 1;

console.log(`\nVolumi da collocare: ${libri.length}`);
console.log(`  con proposta:      ${assegnati.length}`);
console.log(`  senza proposta:    ${scoperti.length}\n`);
console.log('Distribuzione proposta:');
for (const [sez, n] of Object.entries(perSezione).sort((a, b) => b[1] - a[1])) {
  console.log(`  ${String(n).padStart(3)}  ${labelFor(sez)}`);
}
if (scoperti.length) {
  console.log('\nSenza proposta (restano da collocare):');
  for (const s of scoperti) console.log(`  · ${(s.autori || '—').slice(0, 34).padEnd(34)} ${s.title.slice(0, 56)}`);
}

if (APPLICA) {
  const upd = db.prepare(`UPDATE books SET placement_id = ?, placement_at = ?, updated_at = datetime('now') WHERE id = ?`);
  const at = new Date().toISOString();
  db.transaction(list => { for (const a of list) upd.run(a.dove, at, a.id); })(assegnati);
  console.log(`\n✓ Applicate ${assegnati.length} collocazioni.`);
} else {
  const dest = process.argv.find(a => a.startsWith('--elenco='));
  if (dest) {
    require('fs').writeFileSync(dest.slice(9),
      assegnati.map(a => `${labelFor(a.dove)}\t${(a.autori || '—')}\t${a.titolo}`)
        .sort().join('\n'), 'utf8');
    console.log(`\nElenco completo scritto in ${dest.slice(9)}`);
  }
  console.log('\n(anteprima — nessuna modifica scritta. Aggiungi --applica per confermare)');
}
db.close();
